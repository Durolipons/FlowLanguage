// Generates placeholder PNG "photos" for every vocabulary item and writes the
// bundled-image registry (src/content/assets/imageAssets.ts).
// Run with: npm run gen:images
// Replace the PNGs in assets/images/<lang>/ with real photos — the registry
// keys (item ids) stay the same, so no code changes are needed.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const contentDir = join(root, 'src', 'content');

function loadPack(file, varName) {
  let src = readFileSync(join(contentDir, file), 'utf8');
  src = src.replace(/^import[^\n]*\n/m, '');
  src = src.replace(new RegExp(`export const ${varName}: LanguagePack =`), 'return');
  return new Function(src)();
}

// ---- minimal truecolor PNG encoder (8-bit RGB, no deps) ----
const crcTable = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();
function crc32(buf) {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) c = crcTable[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length, 0);
  const typeBuf = Buffer.from(type, 'ascii');
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(Buffer.concat([typeBuf, data])), 0);
  return Buffer.concat([len, typeBuf, data, crc]);
}
function encodePng(width, height, rgb) {
  const sig = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]);
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 2; // color type RGB
  const stride = width * 3;
  const raw = Buffer.alloc((stride + 1) * height);
  for (let y = 0; y < height; y++) {
    raw[y * (stride + 1)] = 0; // filter: none
    rgb.copy(raw, y * (stride + 1) + 1, y * stride, (y + 1) * stride);
  }
  const idat = zlib.deflateSync(raw);
  return Buffer.concat([sig, chunk('IHDR', ihdr), chunk('IDAT', idat), chunk('IEND', Buffer.alloc(0))]);
}

const palette = [
  [99, 102, 241], [14, 165, 233], [16, 185, 129], [245, 158, 11],
  [239, 68, 68], [168, 85, 247], [236, 72, 153], [20, 184, 166],
];
function hash(s) {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
  return h;
}
function makeTile(itemId) {
  const S = 256;
  const buf = Buffer.alloc(S * S * 3);
  const [r, g, b] = palette[hash(itemId) % palette.length];
  for (let y = 0; y < S; y++) {
    for (let x = 0; x < S; x++) {
      const i = (y * S + x) * 3;
      const border = x < 12 || y < 12 || x >= S - 12 || y >= S - 12;
      const dx = x - S / 2;
      const dy = y - S / 2;
      const dot = Math.sqrt(dx * dx + dy * dy) < 44;
      let R = r;
      let G = g;
      let B = b;
      if (border) { R = Math.max(0, r - 50); G = Math.max(0, g - 50); B = Math.max(0, b - 50); }
      if (dot) { R = 255; G = 255; B = 255; }
      buf[i] = R; buf[i + 1] = G; buf[i + 2] = B;
    }
  }
  return encodePng(S, S, buf);
}

const lines = [
  '// AUTO-GENERATED by `npm run gen:images`. These are PLACEHOLDER images.',
  "// Replace the PNGs in assets/images/<lang>/ with real photos; keys stay the same.",
  "import type { ImageSourcePropType } from 'react-native';",
  '',
  'export const imageAssets: Record<string, ImageSourcePropType> = {',
];

let count = 0;
for (const [file, name, prefix] of [
  ['es.ts', 'esPack', 'es'],
  ['fr.ts', 'frPack', 'fr'],
]) {
  const pack = loadPack(file, name);
  const dir = join(root, 'assets', 'images', prefix);
  mkdirSync(dir, { recursive: true });
  for (const item of Object.values(pack.items)) {
    const slug = item.id.replace(/^[a-z]{2}-/, '');
    writeFileSync(join(dir, `${slug}.png`), makeTile(item.id));
    lines.push(`  '${item.id}': require('../../../assets/images/${prefix}/${slug}.png'),`);
    count++;
  }
}
lines.push('};', '', 'export function getImageAsset(itemId: string): ImageSourcePropType | undefined {', '  return imageAssets[itemId];', '}');

mkdirSync(join(root, 'src', 'content', 'assets'), { recursive: true });
writeFileSync(join(root, 'src', 'content', 'assets', 'imageAssets.ts'), lines.join('\n') + '\n');
console.log(`Generated ${count} placeholder images + src/content/assets/imageAssets.ts`);
