r"""Generate expressive dialogue audio with Chatterbox (per-speaker cloning).

Each turn is synthesized in its speaker's voice by cloning from a reference clip
at voices/<lang>_<speaker>.wav (e.g. voices/es_ana.wav). Turns without a clip use
Chatterbox's default voice. Output WAVs go to assets/audio/<lang>/dlg_<id>_<n>.wav
and the bundled registry src/content/assets/dialogueAudio.ts is rebuilt.

Requires Python 3.9-3.11:  pip install chatterbox-tts   (GPU recommended)

Usage:
  npm run tts:manifest                                   # export dialogues.json
  python scripts/tts/generate_dialogues.py --lang es --gpu
  python scripts/tts/generate_dialogues.py               # all languages
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
DIALOGUES = os.path.join(HERE, "dialogues.json")
LANGS = ("es", "fr", "pl")


def main() -> None:
    ap = argparse.ArgumentParser(description="Generate Chatterbox dialogue audio.")
    ap.add_argument("--lang", choices=LANGS, help="only generate this language (registry still covers all)")
    ap.add_argument("--gpu", action="store_true")
    ap.add_argument("--force", action="store_true", help="overwrite existing files")
    args = ap.parse_args()

    if not os.path.exists(DIALOGUES):
        sys.exit(f"Not found: {DIALOGUES} -- run `npm run tts:manifest` first.")
    with open(DIALOGUES, encoding="utf-8") as f:
        all_dialogues = json.load(f)
    if not all_dialogues:
        sys.exit("No dialogues in dialogues.json")

    model = None
    if any(d["language"] == args.lang for d in all_dialogues) if args.lang else True:
        try:
            import torch
            import torchaudio  # noqa: F401
            from chatterbox.mtl_tts import ChatterboxMultilingualTTS
        except Exception as e:
            sys.exit("Chatterbox not available. Install:  pip install chatterbox-tts\n" f"Import error: {e}")
        device = "cuda" if (args.gpu and torch.cuda.is_available()) else "cpu"
        print(f"Loading Chatterbox multilingual on {device} ...")
        model = ChatterboxMultilingualTTS.from_pretrained(device=device)

    registry = {}
    done = failed = skipped = 0
    for d in all_dialogues:
        lang = d["language"]
        out_dir = os.path.join(ROOT, "assets", "audio", lang)
        os.makedirs(out_dir, exist_ok=True)
        target = (args.lang is None) or (lang == args.lang)
        for i, turn in enumerate(d["turns"]):
            key = f"{d['id']}:{i}"
            slug = f"dlg_{d['id']}_{i}"
            out_path = os.path.join(out_dir, f"{slug}.wav")
            if os.path.exists(out_path):
                registry[key] = f"assets/audio/{lang}/{slug}.wav"
                if not target or not args.force:
                    skipped += 1
                    continue
            if not target or model is None:
                continue
            ref = os.path.join(ROOT, "voices", f"{lang}_{turn['speaker']}.wav")
            speaker = ref if os.path.exists(ref) else None
            try:
                wav = model.generate(turn["text"], language_id=lang, audio_prompt_path=speaker)
                wav = wav.cpu()
                if wav.dim() == 1:
                    wav = wav.unsqueeze(0)
                torchaudio.save(out_path, wav, model.sr)
                registry[key] = f"assets/audio/{lang}/{slug}.wav"
                done += 1
                print(f"  ok {key} ({turn['speaker']}) -> assets/audio/{lang}/{slug}.wav")
            except Exception as e:
                failed += 1
                print(f"  FAIL {key}: {e}")

    lines = [
        "// AUTO-GENERATED by scripts/tts/generate_dialogues.py (Chatterbox).",
        "// Dialogue audio keyed by '<dialogueId>:<turnIndex>'. Empty = turns use TTS.",
        "import type { AudioSource } from 'expo-audio';",
        "",
        "export const dialogueAudio: Record<string, AudioSource> = {",
    ]
    for k, v in registry.items():
        lines.append(f"  '{k}': require('../../../{v}'),")
    lines += [
        "};",
        "",
        "export function getDialogueAudioAsset(key: string): AudioSource | undefined {",
        "  return dialogueAudio[key];",
        "}",
        "",
    ]
    with open(os.path.join(ROOT, "src", "content", "assets", "dialogueAudio.ts"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"\nDone. generated={done} skipped={skipped} failed={failed}")
    print("Wrote src/content/assets/dialogueAudio.ts")


if __name__ == "__main__":
    main()
