// Bulk-import real images/audio for vocabulary items from a manifest.
//
// Usage:
//   npm run import:assets                       # link mode: write remote URLs
//   npm run import:assets -- --download         # download files locally + rebundle
//   npm run import:assets -- --manifest assets/manifest.csv
//
// Manifest (JSON):
//   { "images": { "es-agua": "https://…/agua.jpg" },
//     "audio":  { "es-agua": "https://…/agua.mp3" } }
//   ...or an array: [ { "id": "es-agua", "image": "…", "audio": "…" }, … ]
//
// Manifest (CSV, header: id,image,audio):
//   id,image,audio
//   es-agua,https://…/agua.jpg,https://…/agua.mp3
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, extname } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const contentDir = join(root, 'src', 'content');
const assetsDir = join(root, 'assets');
const assetsSrcDir = join(contentDir, 'assets');

const argv = process.argv.slice(2);
const download = argv.includes('--download');
const mi = argv.indexOf('--manifest');
const manifestPath = mi >= 0 ? argv[mi + 1] : join(assetsDir, 'manifest.json');

function loadPack(file, varName) {
  let src = readFileSync(join(contentDir, file), 'utf8');
  src = src.replace(/^import[^\n]*\n/m, '');
  src = src.replace(new RegExp(`export const ${varName}: LanguagePack =`), 'return');
  return new Function(src)();
}
const packs = [loadPack('es.ts', 'esPack'), loadPack('fr.ts', 'frPack')];
const itemIndex = new Map();
for (const p of packs) {
  for (const item of Object.values(p.items)) {
    itemIndex.set(item.id, { prefix: p.code, slug: item.id.replace(/^[a-z]{2}-/, '') });
  }
}

function normalize(obj) {
  const images = {};
  const audio = {};
  if (Array.isArray(obj)) {
    for (const r of obj) {
      if (r && r.id) {
        if (r.image) images[r.id] = r.image;
        if (r.audio) audio[r.id] = r.audio;
      }
    }
  } else {
    Object.assign(images, obj.images || {});
    Object.assign(audio, obj.audio || {});
  }
  return { images, audio };
}
function parseCsv(raw) {
  const lines = raw.split(/\r?\n/).filter((l) => l.trim());
  const header = lines.shift().split(',').map((s) => s.trim().toLowerCase());
  const idx = { id: header.indexOf('id'), image: header.indexOf('image'), audio: header.indexOf('audio') };
  const rows = lines.map((line) => {
    const c = line.split(',').map((s) => s.trim());
    return { id: c[idx.id], image: idx.image >= 0 ? c[idx.image] : '', audio: idx.audio >= 0 ? c[idx.audio] : '' };
  });
  return normalize(rows);
}
function parseManifest(path) {
  const raw = readFileSync(path, 'utf8');
  return path.toLowerCase().endsWith('.csv') ? parseCsv(raw) : normalize(JSON.parse(raw));
}
function validate(map, label) {
  const unknown = Object.keys(map).filter((id) => !itemIndex.has(id));
  if (unknown.length) console.warn(`  ! ${label}: unknown item ids ignored: ${unknown.join(', ')}`);
  return Object.keys(map).length - unknown.length;
}
function writeRemoteAssets(images, audio) {
  const path = join(assetsSrcDir, 'remoteAssets.ts');
  let existing = { images: {}, audio: {} };
  if (existsSync(path)) {
    try {
      const src = readFileSync(path, 'utf8').replace(/^import[^\n]*\n/m, '').replace(/export const/g, 'const');
      existing = new Function(src + '\nreturn { images: remoteImages, audio: remoteAudio };')();
    } catch {
      /* ignore */
    }
  }
  const mi = { ...existing.images, ...images };
  const ma = { ...existing.audio, ...audio };
  const q = (v) => `'${String(v).replace(/'/g, "\\'")}'`;
  const body = (obj) => Object.entries(obj).map(([k, v]) => `  ${q(k)}: ${q(v)},`).join('\n');
  writeFileSync(
    path,
    [
      '// AUTO-GENERATED by `npm run import:assets` (link mode). Remote URLs.',
      'export const remoteImages: Record<string, string> = {',
      body(mi),
      '};',
      '',
      'export const remoteAudio: Record<string, string> = {',
      body(ma),
      '};',
      '',
    ].join('\n')
  );
}
async function pool(tasks, n) {
  const results = new Array(tasks.length);
  let i = 0;
  async function worker() {
    while (i < tasks.length) results[i++] = await tasks[i - 1]();
  }
  await Promise.all(Array.from({ length: Math.min(n, tasks.length) }, worker));
  return results;
}
function extFrom(url, contentType, def) {
  const e = extname(new URL(url).pathname);
  if (e) return e;
  const ct = (contentType || '').toLowerCase();
  if (ct.includes('png')) return '.png';
  if (ct.includes('webp')) return '.webp';
  if (ct.includes('jpeg') || ct.includes('jpg')) return '.jpg';
  if (ct.includes('mpeg') || ct.includes('mp3')) return '.mp3';
  if (ct.includes('wav')) return '.wav';
  if (ct.includes('aac') || ct.includes('m4a')) return '.m4a';
  return def;
}
async function downloadBuffer(url) {
  const res = await fetch(url, { redirect: 'follow' });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  return { buf: Buffer.from(await res.arrayBuffer()), contentType: res.headers.get('content-type') || '' };
}

function regenerateBundled(kind) {
  const base = join(assetsDir, kind);
  const exts = kind === 'images' ? ['.png', '.jpg', '.jpeg', '.webp'] : ['.mp3', '.wav', '.m4a', '.aac', '.ogg'];
  const lines = [];
  for (const p of packs) {
    const dir = join(base, p.code);
    if (!existsSync(dir)) continue;
    const files = readdirSync(dir);
    for (const item of Object.values(p.items)) {
      const slug = item.id.replace(/^[a-z]{2}-/, '');
      const match = files.find((f) => exts.some((e) => f === slug + e));
      if (match) lines.push(`  '${item.id}': require('../../../assets/${kind}/${p.code}/${match}'),`);
    }
  }
  const path = join(assetsSrcDir, kind === 'images' ? 'imageAssets.ts' : 'audioAssets.ts');
  const header =
    kind === 'images'
      ? ['// AUTO-GENERATED. Bundled images (placeholders + any added files).', "import type { ImageSourcePropType } from 'react-native';", '', 'export const imageAssets: Record<string, ImageSourcePropType> = {']
      : ['// AUTO-GENERATED. Bundled audio (any added recordings).', "import type { AudioSource } from 'expo-audio';", '', 'export const audioAssets: Record<string, AudioSource> = {'];
  const fnName = kind === 'images' ? 'getImageAsset' : 'getAudioAsset';
  const fnRet = kind === 'images' ? 'ImageSourcePropType' : 'AudioSource';
  writeFileSync(
    path,
    [...header, ...lines, '};', '', `export function ${fnName}(itemId: string): ${fnRet} | undefined {`, '  return ' + (kind === 'images' ? 'imageAssets' : 'audioAssets') + '[itemId];', '}', ''].join('\n')
  );
}

async function runDownload(map, kind, defExt) {
  const entries = Object.entries(map).filter(([id]) => itemIndex.has(id));
  let ok = 0;
  let fail = 0;
  const tasks = entries.map(([id, url]) => async () => {
    const { prefix, slug } = itemIndex.get(id);
    const dir = join(assetsDir, kind, prefix);
    mkdirSync(dir, { recursive: true });
    for (const f of readdirSync(dir)) if (f.startsWith(slug + '.')) rmSync(join(dir, f));
    try {
      const { buf, contentType } = await downloadBuffer(url);
      const ext = extFrom(url, contentType, defExt);
      writeFileSync(join(dir, `${slug}${ext}`), buf);
      ok++;
      console.log(`  ok ${id} -> assets/${kind}/${prefix}/${slug}${ext}`);
    } catch (e) {
      fail++;
      console.warn(`  FAIL ${id}: ${e.message}`);
    }
  });
  await pool(tasks, 6);
  return { ok, fail };
}

async function main() {
  if (argv.includes('--register-audio') || argv.includes('--register-images')) {
    const kind = argv.includes('--register-audio') ? 'audio' : 'images';
    regenerateBundled(kind);
    const file = kind === 'images' ? 'imageAssets.ts' : 'audioAssets.ts';
    console.log(`Regenerated src/content/assets/${file} from assets/${kind}/ on disk.`);
    return;
  }
  if (!existsSync(manifestPath)) {
    console.error(`Manifest not found: ${manifestPath}`);
    console.error('Create one (see assets/manifest.example.json) or pass --manifest <path>.');
    process.exit(1);
  }
  const { images, audio } = parseManifest(manifestPath);
  console.log(`Manifest: ${manifestPath}  (mode: ${download ? 'download' : 'link'})`);
  const nImg = validate(images, 'images');
  const nAud = validate(audio, 'audio');
  console.log(`  valid image urls: ${nImg}, valid audio urls: ${nAud}`);

  if (download) {
    const ri = await runDownload(images, 'images', '.png');
    const ra = await runDownload(audio, 'audio', '.mp3');
    if (ri.ok || ra.ok) {
      regenerateBundled('images');
      regenerateBundled('audio');
    }
    console.log(`\nDownloaded images ${ri.ok}/${ri.ok + ri.fail}, audio ${ra.ok}/${ra.ok + ra.fail}.`);
    console.log('Bundled registries regenerated from assets/ on disk.');
  } else {
    writeRemoteAssets(images, audio);
    console.log('\nWrote remote URLs to src/content/assets/remoteAssets.ts');
    console.log('(bundled assets still take priority; remove them to use these.)');
  }
}
main();

