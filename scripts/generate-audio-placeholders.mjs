// OPT-IN: generates short placeholder WAV "recordings" for every item and wires
// them into src/content/assets/audioAssets.ts so you can test the recorded-audio
// path. These are obviously placeholder tones — replace them with real
// recordings (same filenames) or edit audioAssets.ts to remove them and fall
// back to TTS. Run with: npm run gen:audio
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const contentDir = join(root, 'src', 'content');

function loadPack(file, varName) {
  let src = readFileSync(join(contentDir, file), 'utf8');
  src = src.replace(/^import[^\n]*\n/m, '');
  src = src.replace(new RegExp(`export const ${varName}: LanguagePack =`), 'return');
  return new Function(src)();
}
function hash(s) {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
  return h;
}

// ---- 16-bit PCM mono WAV encoder ----
function encodeWav(samples, sampleRate) {
  const dataSize = samples.length * 2;
  const buf = Buffer.alloc(44 + dataSize);
  buf.write('RIFF', 0);
  buf.writeUInt32LE(36 + dataSize, 4);
  buf.write('WAVE', 8);
  buf.write('fmt ', 12);
  buf.writeUInt32LE(16, 16);
  buf.writeUInt16LE(1, 20); // PCM
  buf.writeUInt16LE(1, 22); // mono
  buf.writeUInt32LE(sampleRate, 24);
  buf.writeUInt32LE(sampleRate * 2, 28);
  buf.writeUInt16LE(2, 32);
  buf.writeUInt16LE(16, 34);
  buf.write('data', 36);
  buf.writeUInt32LE(dataSize, 40);
  for (let i = 0; i < samples.length; i++) {
    const s = Math.max(-1, Math.min(1, samples[i]));
    buf.writeInt16LE(Math.round(s * 32767), 44 + i * 2);
  }
  return buf;
}
function chime(itemId, sampleRate = 22050) {
  const dur = 0.35;
  const n = Math.floor(sampleRate * dur);
  const base = 420 + (hash(itemId) % 6) * 55;
  const out = new Float64Array(n);
  for (let i = 0; i < n; i++) {
    const t = i / sampleRate;
    const env = Math.exp(-6 * t);
    out[i] = (Math.sin(2 * Math.PI * base * t) * 0.5 + Math.sin(2 * Math.PI * base * 1.5 * t) * 0.25) * env * 0.6;
  }
  return encodeWav(out, sampleRate);
}

const lines = [
  '// AUTO-GENERATED by `npm run gen:audio`. These are PLACEHOLDER tones.',
  '// Replace the WAVs in assets/audio/<lang>/ with real recordings (same',
  '// filenames), or delete entries here to fall back to text-to-speech.',
  "import type { AudioSource } from 'expo-audio';",
  '',
  'export const audioAssets: Record<string, AudioSource> = {',
];

let count = 0;
for (const [file, name, prefix] of [
  ['es.ts', 'esPack', 'es'],
  ['fr.ts', 'frPack', 'fr'],
]) {
  const pack = loadPack(file, name);
  const dir = join(root, 'assets', 'audio', prefix);
  mkdirSync(dir, { recursive: true });
  for (const item of Object.values(pack.items)) {
    const slug = item.id.replace(/^[a-z]{2}-/, '');
    writeFileSync(join(dir, `${slug}.wav`), chime(item.id));
    lines.push(`  '${item.id}': require('../../../assets/audio/${prefix}/${slug}.wav'),`);
    count++;
  }
}
lines.push('};', '', 'export function getAudioAsset(itemId: string): AudioSource | undefined {', '  return audioAssets[itemId];', '}');
writeFileSync(join(root, 'src', 'content', 'assets', 'audioAssets.ts'), lines.join('\n') + '\n');
console.log(`Generated ${count} placeholder WAVs + wired audioAssets.ts`);
